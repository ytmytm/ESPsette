#!/usr/bin/env python3
"""Generate the running firmware's Git identity without rebuilding core libraries."""
import argparse
import json
from pathlib import Path
import subprocess

ROOT = Path(__file__).resolve().parents[1]


def version(root):
    commit = subprocess.check_output(['git', 'rev-parse', 'HEAD'], cwd=root, text=True).strip()
    dirty = subprocess.run(['git', 'diff', '--quiet', 'HEAD', '--'], cwd=root).returncode != 0
    return dict(commit=commit, dirty=dirty, version=commit[:12] + ('-dirty' if dirty else ''))


def write_if_changed(path, text):
    path.parent.mkdir(parents=True, exist_ok=True)
    if not path.exists() or path.read_text() != text:
        path.write_text(text)


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--out', type=Path, default=ROOT / 'include/build_version.h')
    parser.add_argument('--metadata', type=Path)
    parser.add_argument('--show-only', action='store_true', help='Print identity without generating files')
    args = parser.parse_args()
    identity = version(ROOT)
    print(f'Firmware version: {identity["version"]} (commit {identity["commit"]})', flush=True)
    if args.show_only:
        raise SystemExit(0)
    text = ('// Generated by scripts/build-version.py.\n#pragma once\n'
            'static const char FIRMWARE_VERSION[] = ' + json.dumps(identity['version']) + ';\n'
            'static const char FIRMWARE_COMMIT[] = ' + json.dumps(identity['commit']) + ';\n')
    write_if_changed(args.out, text)
    if args.metadata:
        write_if_changed(args.metadata, json.dumps(identity, indent=2) + '\n')
