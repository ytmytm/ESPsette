#!/usr/bin/env python3
"""Assemble C64/TED loaders with ACME and generate the firmware's flash arrays."""
import argparse
from pathlib import Path
import shutil
import subprocess
import tempfile

ROOT = Path(__file__).resolve().parent.parent

def build(output):
    if not shutil.which('acme'):
        raise SystemExit('ACME is required: apt-get install acme (Linux), brew install acme (macOS)')
    arrays = []
    with tempfile.TemporaryDirectory(prefix='espsette-native-') as temporary:
        for ted, name, address in [(0, 'c64', 0x0400), (1, 'ted', 0x0800)]:
            receiver = Path(temporary) / 'receiver.prg'
            stub = Path(temporary) / 'bootstrap.prg'
            subprocess.run(['acme', f'-DC16={ted}', '-DBOOT=1', f'-DORIGIN={address}',
                            '-f', 'cbm', '-o', str(receiver), str(ROOT/'native/fastloader/receiver.asm')], check=True)
            data = receiver.read_bytes()[2:]
            pages = (len(data) + 255) // 256
            subprocess.run(['acme', f'-DC16={ted}', f'-DSTAGE_PAGES={pages}', f'-DSTAGE_ADDR={address}',
                            '-f', 'cbm', '-o', str(stub), str(ROOT/'native/fastloader/bootstrap.asm')], check=True)
            code = stub.read_bytes()[2:]
            early_release = (bytes.fromhex('78 a9 00 85 01 a9 0b 85 00') if ted else
                             bytes.fromhex('78 a9 27 85 00'))
            assert code.startswith(early_release)
            for suffix, content in [('Bootstrap', code), ('Receiver', data.ljust(pages*256, b'\0'))]:
                rows = [', '.join(f'0x{value:02x}' for value in content[i:i+16]) for i in range(0, len(content), 16)]
                arrays.append(f'static const uint8_t {name}{suffix}[] PROGMEM = {{\n  ' + ',\n  '.join(rows) + '\n};\n')
            print(f'{name}: bootstrap {len(code)} B; receiver {len(data)} B ({pages} pages)')
    text = '// Generated by scripts/build-native.py; edit native/fastloader/*.asm.\n#pragma once\n#include <stdint.h>\n#include <pgmspace.h>\n\n' + '\n'.join(arrays)
    output.parent.mkdir(parents=True, exist_ok=True)
    if not output.exists() or output.read_text() != text:
        output.write_text(text)

if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--out', type=Path, default=ROOT/'include/fastloader_native.h')
    build(parser.parse_args().out)
