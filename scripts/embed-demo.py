#!/usr/bin/env python3
"""Embed the original Circles PRG once; standard loading repeats it logically."""
import argparse
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def build(output):
    data = (ROOT / 'assets/demo/circles.prg').read_bytes()
    address = int.from_bytes(data[:2], 'little')
    if len(data) < 3 or address != 0x0801 or address + len(data) - 2 > 0x8000:
        raise ValueError('Circles must be a C64 BASIC PRG within the fastloader RAM range')
    rows = [', '.join(f'0x{x:02x}' for x in data[i:i+16]) for i in range(0, len(data), 16)]
    text = ('// Generated by scripts/embed-demo.py from assets/demo/circles.prg.\n'
            '// Circles: music Shogoon, code YTM. https://csdb.dk/release/?id=262238\n'
            '#pragma once\n#include <stdint.h>\n#include <pgmspace.h>\n\n'
            'static const uint8_t circlesPrg[] PROGMEM = {\n  ' + ',\n  '.join(rows) + '\n};\n')
    output.parent.mkdir(parents=True, exist_ok=True)
    if not output.exists() or output.read_text() != text:
        output.write_text(text)


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--out', type=Path, default=ROOT / 'include/circles_demo.h')
    build(parser.parse_args().out)
